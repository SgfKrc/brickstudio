// 常用色排前面
const PRIORITY = [15, 14, 4, 1, 2, 0, 71, 72, 19, 28, 25, 27, 322, 321, 212, 226, 191,
  10, 288, 320, 70, 308, 84, 5, 29, 26, 22, 3, 378, 379, 484];

function rank(c) {
  const pi = PRIORITY.indexOf(c.code);
  if (pi >= 0) return pi;
  if (!c.alpha && !c.fin) return 100 + c.code;         // 其他实色
  if (c.alpha) return 10000 + c.code;                  // 透明
  return 20000 + c.code;                               // 金属/珠光
}

export const LDRAW_COLORS = GEN
  .filter(c => c.code !== 16 && c.code !== 24)
  .map(c => ({ ...c, name: ZH_NAMES.get(c.code) || c.en }))
  .sort((a, b) => rank(a) - rank(b));

const byCode = new Map(LDRAW_COLORS.map(c => [c.code, c]));

export function colorByCode(code) {
  return byCode.get(code) || { code, name: `颜色 ${code}`, en: `Color ${code}`, hex: '#B040B0' };
}

